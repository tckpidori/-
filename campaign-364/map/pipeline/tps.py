def U(r2): return np.where(r2>0, r2*np.log(r2+1e-12), 0.0)
def norm(lat,lon): return np.stack([(lon-10)/20,(lat-45)/10],-1)
P=norm(CP[:,0],CP[:,1]); n=len(P)
def fit(vals, lam=0.002):
    K=U(((P[:,None,:]-P[None,:,:])**2).sum(-1))+lam*np.eye(n)
    Q=np.hstack([np.ones((n,1)),P])
    A=np.zeros((n+3,n+3)); A[:n,:n]=K; A[:n,n:]=Q; A[n:,:n]=Q.T
    b=np.zeros(n+3); b[:n]=vals
    return np.linalg.solve(A,b)
